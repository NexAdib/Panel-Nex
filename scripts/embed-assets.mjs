#!/usr/bin/env node
// Converts the Vite output in dist/ui into src/worker/assets.gen.ts so the worker
// can serve the panel and portal from memory (no external CDN, no GitHub fetches).
//
//   node scripts/embed-assets.mjs                  embed dist/ui (fails if missing)
//   node scripts/embed-assets.mjs --stub-if-missing  write a tiny placeholder when dist/ui is absent
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const uiDir = join(root, 'dist', 'ui');
const outFile = join(root, 'src', 'worker', 'assets.gen.ts');
const stubMode = process.argv.includes('--stub-if-missing');

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.json': 'application/json; charset=utf-8',
  '.webmanifest': 'application/manifest+json',
  '.woff2': 'font/woff2',
  '.woff': 'font/woff',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
  '.txt': 'text/plain; charset=utf-8',
};
const TEXT = new Set(['.html', '.js', '.css', '.svg', '.json', '.webmanifest', '.txt']);

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else out.push(p);
  }
  return out;
}

function header() {
  return [
    '// AUTO-GENERATED by scripts/embed-assets.mjs — do not edit.',
    '/* biome-ignore-all lint: generated file */',
    'export interface EmbeddedAsset {',
    '  type: string;',
    '  body: string;',
    '  b64: boolean;',
    '  etag: string;',
    '  immutable: boolean;',
    '}',
    '',
  ];
}

if (!existsSync(uiDir)) {
  if (stubMode) {
    if (!existsSync(outFile)) {
      const html =
        '<!doctype html><meta charset="utf-8"><title>NexAdib</title><p>UI not built. Run <code>npm run build:ui</code>.</p>';
      const lines = header();
      lines.push('export const ASSETS: Record<string, EmbeddedAsset> = {');
      for (const name of ['panel.html', 'portal.html']) {
        lines.push(
          `  ${JSON.stringify(name)}: { type: 'text/html; charset=utf-8', body: ${JSON.stringify(html)}, b64: false, etag: '"stub"', immutable: false },`,
        );
      }
      lines.push('};', '');
      writeFileSync(outFile, lines.join('\n'));
      console.log('assets: wrote stub', relative(root, outFile));
    }
    process.exit(0);
  }
  console.error('dist/ui not found — run `vite build` first');
  process.exit(1);
}

const lines = header();
lines.push('export const ASSETS: Record<string, EmbeddedAsset> = {');
let total = 0;
for (const file of walk(uiDir).sort()) {
  const rel = relative(uiDir, file).split('\\').join('/');
  const ext = rel.slice(rel.lastIndexOf('.'));
  const type = TYPES[ext];
  if (!type) continue;
  const buf = readFileSync(file);
  total += buf.length;
  const etag = `"${createHash('sha256').update(buf).digest('base64url').slice(0, 16)}"`;
  const isText = TEXT.has(ext);
  const body = isText ? buf.toString('utf8') : buf.toString('base64');
  const immutable = rel.startsWith('assets/');
  lines.push(
    `  ${JSON.stringify(rel)}: { type: ${JSON.stringify(type)}, body: ${JSON.stringify(body)}, b64: ${!isText}, etag: ${JSON.stringify(etag)}, immutable: ${immutable} },`,
  );
}
lines.push('};', '');
writeFileSync(outFile, lines.join('\n'));
console.log(`assets: embedded ${(total / 1024).toFixed(1)} KiB into ${relative(root, outFile)}`);
